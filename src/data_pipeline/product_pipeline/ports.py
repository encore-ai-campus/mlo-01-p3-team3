"""Structural interfaces used by ingestion and publication application code."""
from pathlib import Path
from typing import ContextManager, Protocol


class ImageStore(Protocol):
    def ensure(self, key: str, source: Path, checksum: str, size: int) -> bool: ...


class EventPublisher(Protocol):
    def send(self, event: dict, key: str): ...


class AuditTrail(Protocol):
    def write(self, relative: str, value: dict): ...
    def registration(self, key: str) -> dict | None: ...


class IngestionLedger(Protocol):
    def exclusive(self) -> ContextManager: ...
    def snapshot(self, manifest: dict): ...
    def register(self, row: dict, manifest: dict, archived: dict | None) -> dict: ...
    def acquire(self, key: str): ...
    def get(self, key: str) -> dict: ...
    def renew(self, key: str, token): ...
    def release(self, key: str, token): ...
    def attempt(self, key: str, stage: str, status: str, execution: str, duration_ms: int, error=None): ...
    def images(self, key: str, token, vector: list): ...
    def ensure_raw(self, document: dict) -> bool: ...
    def update(self, key: str, token, **changes): ...


class PublicationStore(Protocol):
    target: str

    def preflight(self) -> dict: ...
    def transaction(self) -> ContextManager: ...
    def get(self, table: str, key: dict, *, locking: bool = True) -> dict | None: ...
    def identity(self, table: str, key: dict, values: dict) -> tuple: ...
    def update(self, table: str, key: dict, values: dict): ...
    def one(self, sql: str, args=()) -> dict | None: ...
