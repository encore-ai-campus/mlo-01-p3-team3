"""Structural boundaries between orchestration and runtime implementations."""
from typing import Iterable, Protocol


class Source(Protocol):
    identity: dict
    def references(self) -> Iterable[dict]: ...
    def read_many(self, references: list[dict]) -> list[dict]: ...
    def current(self, references: list[dict]) -> bool: ...
    def close(self): ...


class Lake(Protocol):
    identity: dict
    def read_keys(self, table: str, keys: list[str], version=None) -> dict: ...
    def commit(self, table: str, rows: list[dict]) -> dict: ...
    def verify(self, proof: dict): ...
    def close(self): ...


class Publisher(Protocol):
    identity: dict
    def publish(self, delivery: dict) -> dict: ...
    def audit(self, delivery: dict, receipt: dict): ...
    def close(self): ...
